#!/usr/bin/env node
// pin-poster-render.mjs — write library/packet/poster-render.integrity.js, the sha384s the browser checks
// before it runs the served map-sheet generator or uses the served capitals-and-cities table. Run it
// whenever library/packet/poster-render.js or library/scripts/posters/data/ne-places.json changes;
// check:poster-render-pinned fails (and names this command) until the pins match the files again.
//
//   node library/scripts/posters/pin-poster-render.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { join, dirname } from 'node:path'

const LIB = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'packet')
export const pinOf = (text) => `sha384-${createHash('sha384').update(text, 'utf8').digest('base64')}`

// The CLASSIC-SCRIPT copy of the generator, for pages whose Content-Security-Policy forbids blob: scripts:
// loaded with <script integrity=…> the browser verifies it natively. poster-render.js has one export and
// no imports, so the transform is mechanical — strict mode kept (modules are strict), the one export
// becomes window.DoxaPosterRender. generate-tree writes it with THIS function, so the served copy and the
// pin cannot disagree about what it is.
export function globalVariant(source) {
  const body = String(source).replace(/^export function createPosterGenerator\(/m, 'function createPosterGenerator(')
  if (body === String(source)) throw new Error('poster-render.js no longer exports createPosterGenerator as the transform expects')
  return `(function () {\n'use strict';\n${body}\nglobalThis.DoxaPosterRender = { createPosterGenerator };\n})();\n`
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const pin = pinOf(readFileSync(join(LIB, 'poster-render.js'), 'utf8'))
  const places = pinOf(readFileSync(join(LIB, '..', 'scripts', 'posters', 'data', 'ne-places.json'), 'utf8'))
  const classic = pinOf(globalVariant(readFileSync(join(LIB, 'poster-render.js'), 'utf8')))
  const strings = pinOf(readFileSync(join(LIB, '..', 'scripts', 'posters', 'packet-strings.json'), 'utf8'))
  writeFileSync(join(LIB, 'poster-render.integrity.js'), `// GENERATED by library/scripts/posters/pin-poster-render.mjs — do not edit by hand.
// The sha384 of library/packet/poster-render.js. The browser fetches the served copy of that file
// (<assets>/lib/poster-render.js), hashes it, and runs it only when it matches this pin: code loaded at
// print time is integrity-pinned like every embed, because it executes on partner pages.
export const POSTER_RENDER_SHA384 = '${pin}'
// The sha384 of library/scripts/posters/data/ne-places.json, served at <assets>/boundaries/ne-places.json.
// Data, not code, but pinned the same way: a sheet uses the places only when they are the pinned ones.
export const NE_PLACES_SHA384 = '${places}'
// The sha384 of the classic-script copy (<assets>/lib/poster-render.global.js, globalVariant of the file above),
// loaded with <script integrity> where a page's policy forbids importing a blob: of the verified text.
export const POSTER_RENDER_GLOBAL_SHA384 = '${classic}'
// The sha384 of library/scripts/posters/packet-strings.json, served at <assets>/lib/packet-strings.json. The
// packet, list and card text in every language, fetched at print time (packet/packetStrings.js) and used only
// when it matches; otherwise the print falls back to the bundled English block.
export const PACKET_STRINGS_SHA384 = '${strings}'
`)
  console.log(`[pin-poster-render] ${pin}\n[pin-poster-render] ne-places ${places}\n[pin-poster-render] classic ${classic}\n[pin-poster-render] packet-strings ${strings}`)
}
